/// «دفتر مربی قرآن» — the two ways a parent or the teacher first meets it.
///
/// 1. The tool is reachable only from the More page, so the grid row is the
///    entry point that actually matters: a registry entry that no longer
///    matches its route leaves the whole section unreachable while every
///    screen test still passes.
/// 2. «گزارش والدین» is what the teacher sends home, and its paragraph is
///    generated by templates before being edited by hand. The tests pin the
///    generated text, the toggles that regenerate it, and the closing line —
///    the parts a wrong edit would quietly change.
///
/// The DB is a real file, not a fake: the report reads the student profile
/// through the DAO, and a fake would let the profile's own SQL drift away
/// from the screen that prints it.
void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  const everyDay = 0x7F;

  group('opening from the worship grid', () {
    late Directory tempDir;
    late AppDatabase db;
    late QuranTeacherDao dao;

    setUp(() async {
      SharedPreferences.setMockInitialValues({});
      tempDir = await Directory.systemTemp.createTemp('teacher_grid_test');
      db = AppDatabase.withConnection(
          NativeDatabase(File(p.join(tempDir.path, 'grid.sqlite'))));
      dao = QuranTeacherDao(db);
      await db.customStatement('SELECT 1');
      await dao.settings();
      await dao.saveClass(
        id: 'c1',
        name: 'حلقهٔ فجر',
        place: 'مسجد',
      );
      await dao.saveStudent(id: 's1', classId: 'c1', name: 'علی');
    });

    tearDown(() async {
      await db.close();
      try {
        if (tempDir.existsSync()) tempDir.deleteSync(recursive: true);
      } on FileSystemException {
        // Windows keeps the handle for a moment; the OS reclaims the temp dir.
      }
    });

    test('the registry files the tool under worship, at its own route', () {
      final item = kMoreItems.firstWhere((i) => i.id == 'quran-teacher');
      expect(item.group, MoreGroup.worship,
          reason: 'the section lives in عبادات, not in the tools group');
      expect(item.kind, MoreKind.route);
      expect(item.destination, RouteNames.quranTeacherHome);
    });

    testWidgets('its tile opens the real class home, not a placeholder',
        (tester) async {
      tester.view.physicalSize = const Size(420 * 3, 2600 * 3);
      tester.view.devicePixelRatio = 3;
      addTearDown(tester.view.reset);

      final router = GoRouter(
        initialLocation: '/more',
        routes: [
          GoRoute(path: '/more', builder: (_, __) => const MoreScreen()),
          GoRoute(
            path: RouteNames.quranTeacherHome,
            builder: (_, __) => const QuranTeacherHomeScreen(),
          ),
        ],
      );

      await _pump(tester, db, MaterialApp.router(routerConfig: router));

      // The tile is on the page before the tap, so the failure says which
      // half broke: the grid or the route behind it.
      expect(find.text('دفتر مربی قرآن'), findsOneWidget);

      await tester.tap(find.text('دفتر مربی قرآن'));
      await tester.pump();
      for (var i = 0; i < 6; i++) {
        await tester.pump(const Duration(milliseconds: 150));
      }

      expect(find.text('حلقهٔ فجر'), findsWidgets,
          reason: 'the real class home lists the seeded class');
      expect(find.text('هنوز کلاسی ثبت نشده'), findsNothing);
      expect(tester.takeException(), isNull);
    });
  });

  group('an empty class', () {
    late Directory tempDir;
    late AppDatabase db;

    setUp(() async {
      SharedPreferences.setMockInitialValues({});
      tempDir = await Directory.systemTemp.createTemp('teacher_empty');
      db = AppDatabase.withConnection(
          NativeDatabase(File(p.join(tempDir.path, 'empty.sqlite'))));
      final dao = QuranTeacherDao(db);
      await db.customStatement('SELECT 1');
      await dao.settings();
      await dao.saveClass(
        id: 'c-empty',
        name: 'حلقهٔ فجر',
        weekdaysMask: 0x7F,
      );
    });

    tearDown(() async {
      await db.close();
      try {
        if (tempDir.existsSync()) tempDir.deleteSync(recursive: true);
      } on FileSystemException {
        // Windows holds the handle for a moment; the OS reclaims the temp dir.
      }
    });

    testWidgets('points at the roster instead of two dead buttons',
        (tester) async {
      await _pump(tester, db, const QuranTeacherHomeScreen());

      // Attendance needs a roster, so «همه حاضر» and «ثبت جلسه» would be dead;
      // the page offers the one action that actually helps instead.
      expect(find.text('هنوز شاگردی در این کلاس نیست'), findsOneWidget);
      expect(find.text('افزودن شاگرد'), findsOneWidget);
      expect(find.text('همه حاضر'), findsNothing);
      expect(tester.takeException(), isNull);
    });
  });

  group('the parent report', () {
    late Directory tempDir;
    late AppDatabase db;
    late QuranTeacherDao dao;

    /// Today in the teacher's own day-key form, so the month window the report
    /// computes actually contains the seeded lesson.
    final todayKey = teacherDayKey(DateTime.now());

    setUp(() async {
      SharedPreferences.setMockInitialValues({});
      tempDir = await Directory.systemTemp.createTemp('teacher_report_test');
      // In-memory: the report's reads are what is under test, not the file
      // layer, and a memory database cannot be left holding a handle between
      // tests.
      db = AppDatabase.withConnection(NativeDatabase.memory());
      dao = QuranTeacherDao(db);
      await db.customStatement('SELECT 1');
      await dao.settings();
      await dao.saveClass(
        id: 'c1',
        name: 'حلقهٔ فجر',
        place: 'مسجد',
      );
      await dao.saveStudent(id: 's1', classId: 'c1', name: 'علی رضایی');
      await dao.saveSettings(const TeacherSettingsRecord(
        className: 'حلقهٔ فجر',
        mosqueName: 'مسجد النبی',
        teacherName: 'استاد رضایی',
        excusedExcluded: false,
      ));

      final session = await dao.ensureTodaySession(
        classId: 'c1',
        dayKey: todayKey,
        weekdaysMask: everyDay,
        now: DateTime.now(),
      );
      expect(session, isNotNull);
      await dao.setAttendance(
        sessionId: session!.id,
        studentId: 's1',
        status: AttendanceStatus.present,
      );
      final saved = await dao.saveLesson(
        id: 'l1',
        sessionId: session.id,
        studentId: 's1',
        dayKey: todayKey,
        type: LessonType.recitation,
        pageStart: 3,
        pageEnd: 5,
        gradeKey: 'excellent',
        mistakeCount: 1,
        tajweedTags: const ['madd'],
        nextPageStart: 9,
      );
      expect(saved, isTrue);
    });

    tearDown(() async {
      await db.close();
      try {
        if (tempDir.existsSync()) tempDir.deleteSync(recursive: true);
      } on FileSystemException {
        // Windows keeps the handle for a moment; the OS reclaims the temp dir.
      }
    });

    testWidgets('seeds the editable paragraph from the student’s own record',
        (tester) async {
      await _pump(
        tester,
        db,
        const ParentReportScreen(studentId: 's1'),
      );

      expect(find.text('گزارش والدین'), findsOneWidget);
      expect(find.text('تنظیمات گزارش'), findsOneWidget);
      expect(find.text('متن گزارش (قابل ویرایش)'), findsOneWidget);
      expect(find.text('پیش‌نمایش'), findsOneWidget);

      // The four switches, each a template condition.
      for (final label in ['نمره‌ها', 'اشتباه‌ها', 'نام مربی', 'تکلیف بعدی']) {
        expect(find.text(label), findsOneWidget, reason: 'missing $label');
      }

      final text = _paragraph(tester);
      // The report knows the attendance percentage, not the raw session count,
      // so the template prints its percentage form.
      expect(text, contains('میزان حضور در این دوره'),
          reason: 'attendance comes from the seeded present row');
      expect(text, contains('پیشرفت این دوره:'),
          reason: 'the lesson pages are progress, with no judgement');
      expect(text, contains('میانگین نمرهٔ درس‌ها'),
          reason: 'the grade scale asset turns «excellent» into an average');
      expect(text, contains('تکلیف جلسهٔ بعد:'),
          reason: 'the next page is offered, not invented');

      // Buttons that hand the report to somebody else.
      expect(find.text('اشتراک تصویر'), findsOneWidget);
      expect(find.text('PDF'), findsOneWidget);
      expect(find.text('اشتراک متن'), findsOneWidget);
      expect(tester.takeException(), isNull);
    });

    testWidgets('the preview carries the closing line and the teacher’s name',
        (tester) async {
      await _pump(
        tester,
        db,
        const ParentReportScreen(studentId: 's1'),
      );

      await tester.scrollUntilVisible(find.text('گزارش پیشرفت'), 300,
          scrollable: find.byType(Scrollable).first);
      expect(find.text('گزارش پیشرفت'), findsOneWidget);
      expect(find.textContaining('با سپاس از همراهی شما.'), findsOneWidget);
      expect(find.textContaining('استاد رضایی'), findsWidgets);

      // Turning the name off removes it from the closing line — the switch is
      // a promise about what is printed, not a stored preference.
      await tester.tap(find.text('نام مربی'));
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 200));
      expect(find.textContaining('استاد رضایی'), findsNothing);
      expect(find.textContaining('با سپاس از همراهی شما.'), findsOneWidget);
      expect(tester.takeException(), isNull);
    });

    testWidgets('turning the grades off regenerates the paragraph itself',
        (tester) async {
      await _pump(
        tester,
        db,
        const ParentReportScreen(studentId: 's1'),
      );

      expect(_paragraph(tester), contains('میانگین نمرهٔ درس‌ها'));

      await tester.tap(find.text('نمره‌ها'));
      await tester.pump();
      await tester.pump(const Duration(milliseconds: 200));

      final text = _paragraph(tester);
      expect(text, isNot(contains('میانگین نمرهٔ درس‌ها')),
          reason: 'an off switch must not leave the sentence behind');
      // The rest of the report survives: this rebuilds, it does not clear.
      expect(text, contains('میزان حضور در این دوره'));
      expect(text, contains('پیشرفت این دوره:'));
      expect(tester.takeException(), isNull);
    });

    testWidgets('an unknown student says so instead of printing an empty report',
        (tester) async {
      await _pump(
        tester,
        db,
        const ParentReportScreen(studentId: 'missing'),
      );

      expect(find.text('این شاگرد پیدا نشد.'), findsOneWidget);
      expect(find.byType(TextField), findsNothing);
      expect(tester.takeException(), isNull);
    });
  });
}

/// The generated paragraph lives in the screen's only text field.
String _paragraph(WidgetTester tester) {
  final field = tester.widget<TextField>(find.byType(TextField));
  return field.controller?.text ?? '';
}

/// Pumps a teacher screen over the real database.
///
/// The reminder scheduler is silenced: its job is to post notifications, and a
/// test binding has no plugin behind them — the report and the grid do not
/// depend on it either way.
Future<void> _pump(
  WidgetTester tester,
  AppDatabase db,
  Widget child,
) async {
  tester.view.physicalSize = const Size(420 * 3, 1800 * 3);
  tester.view.devicePixelRatio = 3;
  addTearDown(tester.view.reset);

  final idleTicker = clockTickerProvider.overrideWith((ref) {
    final ticker = ClockTicker.idle();
    ref.onDispose(ticker.dispose);
    return ticker;
  });
  final mockRepo = MockSettingsRepository()
    ..setMockSettings(const AppSettings());

  final errors = <FlutterErrorDetails>[];
  final previous = FlutterError.onError;
  FlutterError.onError = errors.add;
  await tester.pumpWidget(
    ProviderScope(
      overrides: [
        appDatabaseProvider.overrideWithValue(db),
        settingsRepositoryProvider.overrideWith((ref) async => mockRepo),
        quranTeacherRemindersServiceProvider
            .overrideWith((ref) => _SilentReminders()),
        // The real store reads its JSON through `rootBundle`; in a widget test
        // that future is cached per test zone, so a second test awaiting the
        // same asset never resumes. A fixed set keeps the grade scale — the
        // only template the report prints — deterministic and zone-free.
        templateStoreProvider.overrideWith((ref) => _FixedTemplates(db)),
        idleTicker,
      ],
      child: MaterialApp(
        theme: AppTheme.lightTheme(),
        home: MediaQuery(
          data: const MediaQueryData(
            size: Size(420, 1800),
            textScaler: TextScaler.linear(1.0),
          ),
          child: Directionality(
            textDirection: TextDirection.rtl,
            child: child,
          ),
        ),
      ),
    ),
  );
  // The screens read a real SQLite file, so their futures only complete
  // inside `runAsync`; and never `pumpAndSettle`, because the More page's hero
  // strip keeps a ticker attached and "settled" is a state it never reaches.
  for (var i = 0; i < 400; i++) {
    await tester.runAsync(
        () => Future<void>.delayed(const Duration(milliseconds: 20)));
    await tester.pump();
    final ready = find.byType(TextField).evaluate().isNotEmpty ||
        find.text('این شاگرد پیدا نشد.').evaluate().isNotEmpty ||
        find.text('حلقهٔ فجر').evaluate().isNotEmpty;
    if (i >= 4 && ready) break;
  }
  await tester.pump(const Duration(milliseconds: 200));
  FlutterError.onError = previous;
  tester.takeException();
  expect(errors, isEmpty,
      reason: errors.map((e) => e.toString()).join(' | '));
}

/// Templates without the asset bundle: the same four grade keys the shipped
/// `grade_scale.json` carries, and nothing that needs a platform channel.
class _FixedTemplates extends TemplateStore {
  _FixedTemplates(super.db);

  @override
  Future<Personal2Templates> load({bool refresh = false}) async =>
      const Personal2Templates(
        habits: [],
        rewards: [],
        tajweedTags: [
          TajweedTag(key: 'madd', titleFa: 'مدّ'),
        ],
        grades: [
          GradeScaleEntry(key: 'excellent', titleFa: 'عالی', value: 4),
          GradeScaleEntry(key: 'good', titleFa: 'خوب', value: 3),
          GradeScaleEntry(key: 'average', titleFa: 'متوسط', value: 2),
          GradeScaleEntry(key: 'needs_practice', titleFa: 'نیاز به تمرین', value: 1),
        ],
      );
}

/// Schedules nothing: the real service posts notifications through a plugin
/// that does not exist under `flutter test`.
class _SilentReminders extends QuranTeacherReminders {
  @override
  Future<int> sync({
    required TeacherSettingsRecord settings,
    required List<ClassGroupRecord> classes,
    required List<String> unrecordedClassNames,
    required DateTime now,
  }) async =>
      0;
}
