/// Data model for «دفتر مالی» (stage 2 of the personal tools).
///
/// Pure Dart: no Flutter, no Drift. The repository maps rows to these values
/// and the widgets read them, so every rule can be unit-tested without a
/// database.
///
/// **No fiqh lives here.** An obligation is an amount, a date and a note; the
/// debt ledger records who owes whom and the payments made. The app never
/// computes interest, never issues a ruling and never sends a message on its
/// own (the «یادآوری مؤدبانه» only hands text to the system share sheet).
library;

import 'package:tawheeed/shared/utils/app_logger.dart';

/// What kind of obligation this row is. The key is the stored value.
enum ObligationKind {
  installment('installment', 'قسط'),
  cheque('cheque', 'چک'),
  loan('loan', 'وام'),
  other('other', 'سایر');

  const ObligationKind(this.key, this.labelFa);

  final String key;
  final String labelFa;

  /// Cheques and «other» are the two directions a person can receive;
  /// installments and loans default to money going out.
  ObligationDirection get defaultDirection =>
      this == ObligationKind.cheque || this == ObligationKind.other
          ? ObligationDirection.receive
          : ObligationDirection.pay;

  /// A cheque is usually known further ahead than an installment.
  int get defaultRemindBeforeDays => this == ObligationKind.cheque ? 7 : 3;

  static ObligationKind fromKey(String value) => ObligationKind.values
      .firstWhere((k) => k.key == value, orElse: () => ObligationKind.other);
}

/// Which way the money moves. `pay` = I owe it, `receive` = it comes to me.
enum ObligationDirection {
  pay('pay', 'پرداختی'),
  receive('receive', 'دریافتی');

  const ObligationDirection(this.key, this.labelFa);

  final String key;
  final String labelFa;

  static ObligationDirection fromKey(String value) =>
      ObligationDirection.values.firstWhere(
        (d) => d.key == value,
        orElse: () => ObligationDirection.pay,
      );
}

enum ObligationStatus {
  pending('pending', 'در انتظار'),
  paid('paid', 'پرداخت‌شده'),
  postponed('postponed', 'به تعویق افتاده'),
  cancelled('cancelled', 'لغو‌شده');

  const ObligationStatus(this.key, this.labelFa);

  final String key;
  final String labelFa;

  /// Paid and cancelled rows leave the timeline and the totals.
  bool get isActive => this == ObligationStatus.pending ||
      this == ObligationStatus.postponed;

  static ObligationStatus fromKey(String value) => ObligationStatus.values
      .firstWhere((s) => s.key == value, orElse: () => ObligationStatus.pending);
}

/// One cheque, one installment, one loan payment or one loose commitment.
class Obligation {
  const Obligation({
    required this.id,
    required this.kind,
    required this.direction,
    required this.title,
    required this.amount,
    required this.dueDate,
    required this.createdAt,
    this.counterparty = '',
    this.status = ObligationStatus.pending,
    this.paidDate,
    this.paidAmount,
    this.planId,
    this.installmentNo,
    this.chequeNumber = '',
    this.bankName = '',
    this.note = '',
    this.remindBeforeDays = 3,
    this.attachmentPaths = const [],
  });

  final String id;
  final ObligationKind kind;
  final ObligationDirection direction;
  final String title;
  final String counterparty;
  final double amount;

  /// Day-granular (`yyyy-MM-dd` in storage).
  final DateTime dueDate;
  final ObligationStatus status;
  final DateTime? paidDate;
  final double? paidAmount;

  /// Set for rows generated by an [InstallmentPlan].
  final String? planId;
  final int? installmentNo;

  final String chequeNumber;
  final String bankName;
  final String note;
  final int remindBeforeDays;
  final List<String> attachmentPaths;
  final DateTime createdAt;

  bool get isPaid => status == ObligationStatus.paid;
  bool get isPayable => direction == ObligationDirection.pay;

  Obligation copyWith({
    ObligationKind? kind,
    ObligationDirection? direction,
    String? title,
    String? counterparty,
    double? amount,
    DateTime? dueDate,
    ObligationStatus? status,
    Object? paidDate = _sentinel,
    Object? paidAmount = _sentinel,
    Object? planId = _sentinel,
    Object? installmentNo = _sentinel,
    String? chequeNumber,
    String? bankName,
    String? note,
    int? remindBeforeDays,
    List<String>? attachmentPaths,
  }) {
    return Obligation(
      id: id,
      kind: kind ?? this.kind,
      direction: direction ?? this.direction,
      title: title ?? this.title,
      counterparty: counterparty ?? this.counterparty,
      amount: (amount as num?)?.toDouble() ?? this.amount,
      dueDate: dueDate ?? this.dueDate,
      status: status ?? this.status,
      paidDate: paidDate == _sentinel ? this.paidDate : paidDate as DateTime?,
      paidAmount: paidAmount == _sentinel
          ? this.paidAmount
          : (paidAmount as num?)?.toDouble(),
      planId: planId == _sentinel ? this.planId : planId as String?,
      installmentNo: installmentNo == _sentinel
          ? this.installmentNo
          : installmentNo as int?,
      chequeNumber: chequeNumber ?? this.chequeNumber,
      bankName: bankName ?? this.bankName,
      note: note ?? this.note,
      remindBeforeDays: remindBeforeDays ?? this.remindBeforeDays,
      attachmentPaths: attachmentPaths ?? this.attachmentPaths,
      createdAt: createdAt,
    );
  }
}

const Object _sentinel = Object();

/// A repeating schedule (installments or a loan) that OWNS its rows.
///
/// Creating the plan generates the obligations; editing it rewrites only the
/// unpaid future ones; deleting it asks about the unpaid ones.
class InstallmentPlan {
  const InstallmentPlan({
    required this.id,
    required this.title,
    required this.kind,
    required this.firstDueDate,
    required this.count,
    required this.amount,
    required this.createdAt,
    this.counterparty = '',
    this.intervalMonths = 1,
    this.totalAmount,
    this.note = '',
  });

  final String id;
  final String title;

  /// [ObligationKind.installment] or [ObligationKind.loan] only.
  final ObligationKind kind;

  /// Jalali day preserved month-to-month (see `financeAddJalaliMonths`).
  final DateTime firstDueDate;
  final int count;
  final double amount;
  final int intervalMonths;

  /// Display-only: what the seller calls the total. Never used in a sum.
  final double? totalAmount;
  final String counterparty;
  final String note;
  final DateTime createdAt;

  /// `count × amount`, for the plan header.
  double get plannedTotal => amount * count;

  InstallmentPlan copyWith({
    String? title,
    String? counterparty,
    DateTime? firstDueDate,
    int? count,
    double? amount,
    int? intervalMonths,
    Object? totalAmount = _sentinel,
    String? note,
  }) {
    return InstallmentPlan(
      id: id,
      title: title ?? this.title,
      kind: kind,
      firstDueDate: firstDueDate ?? this.firstDueDate,
      count: count ?? this.count,
      amount: (amount as num?)?.toDouble() ?? this.amount,
      intervalMonths: intervalMonths ?? this.intervalMonths,
      totalAmount: totalAmount == _sentinel
          ? this.totalAmount
          : (totalAmount as num?)?.toDouble(),
      counterparty: counterparty ?? this.counterparty,
      note: note ?? this.note,
      createdAt: createdAt,
    );
  }
}

/// Someone I owe, or someone who owes me. Name is typed by the user: no
/// contact permission is ever requested.
class Person {
  const Person({
    required this.id,
    required this.name,
    required this.createdAt,
    this.phone = '',
    this.note = '',
  });

  final String id;
  final String name;
  final String phone;
  final String note;
  final DateTime createdAt;

  Person copyWith({String? name, String? phone, String? note}) => Person(
        id: id,
        name: name ?? this.name,
        phone: phone ?? this.phone,
        note: note ?? this.note,
        createdAt: createdAt,
      );
}

enum DebtDirection {
  owedToMe('owed_to_me', 'طلب من'),
  iOwe('i_owe', 'بدهی من');

  const DebtDirection(this.key, this.labelFa);

  final String key;
  final String labelFa;

  static DebtDirection fromKey(String value) => DebtDirection.values.firstWhere(
        (d) => d.key == value,
        orElse: () => DebtDirection.owedToMe,
      );
}

/// One ledger line: a person owes me X, or I owe them X.
class DebtEntry {
  const DebtEntry({
    required this.id,
    required this.personId,
    required this.direction,
    required this.amount,
    required this.createdDate,
    this.dueDate,
    this.note = '',
    this.witnessNote = '',
    this.closed = false,
  });

  final String id;
  final String personId;
  final DebtDirection direction;
  final double amount;
  final DateTime createdDate;

  /// Optional — most informal loans have no agreed date.
  final DateTime? dueDate;
  final String note;

  /// «شاهد» note: who was present. Free text, never a legal claim.
  final String witnessNote;
  final bool closed;

  DebtEntry copyWith({
    DebtDirection? direction,
    double? amount,
    Object? dueDate = _sentinel,
    String? note,
    String? witnessNote,
    bool? closed,
  }) =>
      DebtEntry(
        id: id,
        personId: personId,
        direction: direction ?? this.direction,
        amount: (amount as num?)?.toDouble() ?? this.amount,
        createdDate: createdDate,
        dueDate: dueDate == _sentinel ? this.dueDate : dueDate as DateTime?,
        note: note ?? this.note,
        witnessNote: witnessNote ?? this.witnessNote,
        closed: closed ?? this.closed,
      );
}

/// A (possibly partial) payment against a [DebtEntry].
class DebtPayment {
  const DebtPayment({
    required this.id,
    required this.entryId,
    required this.date,
    required this.amount,
    this.note = '',
  });

  final String id;
  final String entryId;
  final DateTime date;
  final double amount;
  final String note;
}

/// Everything the finance page needs, in one read.
class FinanceSnapshot {
  const FinanceSnapshot({
    this.plans = const [],
    this.obligations = const [],
    this.persons = const [],
    this.entries = const [],
    this.payments = const [],
  });

  final List<InstallmentPlan> plans;
  final List<Obligation> obligations;
  final List<Person> persons;
  final List<DebtEntry> entries;
  final List<DebtPayment> payments;

  bool get isEmpty =>
      obligations.isEmpty && entries.isEmpty && plans.isEmpty && persons.isEmpty;

  List<Obligation> obligationsOfPlan(String planId) =>
      obligations.where((o) => o.planId == planId).toList();

  List<DebtEntry> entriesOfPerson(String personId) =>
      entries.where((e) => e.personId == personId).toList();

  List<DebtPayment> paymentsOf(String entryId) =>
      payments.where((p) => p.entryId == entryId).toList();

  Person? personById(String id) {
    for (final p in persons) {
      if (p.id == id) return p;
    }
    return null;
  }

  InstallmentPlan? planById(String id) {
    for (final p in plans) {
      if (p.id == id) return p;
    }
    return null;
  }
}

/// A defensive parse helper shared by the repository: an unreadable amount
/// becomes 0 rather than throwing inside a list build.
double financeReadAmount(Object? raw) {
  if (raw is num) return raw.toDouble();
  if (raw is String) {
    final parsed = double.tryParse(raw);
    if (parsed != null) return parsed;
  }
  AppLogger.warning('FinanceModel', 'unreadable amount: $raw');
  return 0;
}
