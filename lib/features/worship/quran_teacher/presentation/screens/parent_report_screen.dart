/// «گزارش والدین» — the report builder.
///
/// The paragraph is generated by templates and then handed to the teacher in an
/// EDITABLE text box before anything is shared, which is the brief's rule and
/// also the honest one: the teacher knows the student, the template does not.
class ParentReportScreen extends ConsumerStatefulWidget {
  const ParentReportScreen({super.key, required this.studentId});

  final String studentId;

  @override
  ConsumerState<ParentReportScreen> createState() => _ParentReportScreenState();
}

class _ParentReportScreenState extends ConsumerState<ParentReportScreen> {
  final GlobalKey _cardKey = GlobalKey();
  final TextEditingController _textCtrl = TextEditingController();

  bool _includeGrades = true;
  bool _includeMistakes = true;
  bool _includeTeacherName = true;
  bool _includeNext = true;
  bool _seeded = false;
  bool _sharing = false;

  @override
  void dispose() {
    _textCtrl.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final profile = ref.watch(quranStudentProfileProvider(widget.studentId));

    return Directionality(
      textDirection: TextDirection.rtl,
      child: Scaffold(
        backgroundColor: Colors.transparent,
        appBar: SectionAppBar(
          accent: Personal2Colors.teacher,
          title: 'گزارش والدین',
          leading: IconButton(
            icon: const Icon(Icons.arrow_back),
            tooltip: 'بازگشت',
            onPressed: () => context.pop(),
          ),
        ),
        body: SafeArea(
          child: profile.when(
            loading: () => const Center(child: CircularProgressIndicator()),
            error: (e, _) => FailureView(
              id: 'quran_parent_report_load',
              title: 'گزارش والدین باز نشد',
              detail: 'گزارش پاک نشده است؛ فقط خواندنش ناموفق بود.',
              onRetry: () => ref.invalidate(
                  quranStudentProfileProvider(widget.studentId)),
              layout: FailureLayout.page,
              error: e,
            ),
            data: (state) => state == null
                ? const Center(child: Text('این شاگرد پیدا نشد.'))
                : _body(context, state),
          ),
        ),
      ),
    );
  }

  Widget _body(BuildContext context, StudentProfileState state) {
    final t = TimeThemeKit.of(context).palette;
    const accent = Personal2Colors.teacher;
    final facts = _facts(state, ref.watch(personal2TemplatesProvider).value);

    // Seed the editable paragraph once; re-seeding on every rebuild would
    // overwrite the teacher's edits mid-typing.
    if (!_seeded) {
      _seeded = true;
      _textCtrl.text = [
        ...buildReportParagraphs(
          facts,
          includeGrades: _includeGrades,
        ),
      ].join('\n\n');
    }

    return ListView(
      padding: const EdgeInsets.fromLTRB(DsSpacing.page, 12, DsSpacing.page, 40),
      children: [
        const SectionHeader(title: 'تنظیمات گزارش', accent: accent),
        const SizedBox(height: 6),
        AppCard(
          child: Column(
            children: [
              _toggle('نمره‌ها', _includeGrades,
                  (v) => _rebuild(facts, grades: v)),
              _toggle('اشتباه‌ها', _includeMistakes,
                  (v) => setState(() => _includeMistakes = v)),
              _toggle('نام مربی', _includeTeacherName,
                  (v) => setState(() => _includeTeacherName = v)),
              _toggle('تکلیف بعدی', _includeNext,
                  (v) => setState(() => _includeNext = v)),
            ],
          ),
        ),
        const SizedBox(height: 14),
        const SectionHeader(title: 'متن گزارش (قابل ویرایش)', accent: accent),
        const SizedBox(height: 6),
        AppCard(
          child: TextField(
            controller: _textCtrl,
            maxLines: null,
            minLines: 8,
            style: TextStyle(
              fontFamily: AppTheme.fontFamily,
              fontSize: 13,
              height: 1.9,
              color: t.textPrimary,
            ),
            decoration: const InputDecoration(border: InputBorder.none),
          ),
        ),
        const SizedBox(height: 14),
        const SectionHeader(title: 'پیش‌نمایش', accent: accent),
        const SizedBox(height: 6),
        RepaintBoundary(
          key: _cardKey,
          child: _previewCard(context, state, facts),
        ),
        const SizedBox(height: 16),
        Row(
          children: [
            Expanded(
              child: FilledButton.icon(
                onPressed: _sharing ? null : () => _shareImage(state),
                style: FilledButton.styleFrom(backgroundColor: accent),
                icon: const Icon(Icons.image_rounded, size: 18),
                label: const Text('اشتراک تصویر'),
              ),
            ),
            const SizedBox(width: 8),
            Expanded(
              child: OutlinedButton.icon(
                onPressed: _sharing ? null : () => _sharePdf(state, facts),
                icon: const Icon(Icons.picture_as_pdf_rounded, size: 18),
                label: const Text('PDF'),
              ),
            ),
          ],
        ),
        const SizedBox(height: 8),
        OutlinedButton.icon(
          onPressed: () => ShareService.shareText(
            '${_textCtrl.text}\n\n${ShareService.appLine('دفتر مربی قرآن')}',
            subject: 'گزارش ${state.student.name}',
          ),
          icon: const Icon(Icons.text_snippet_rounded, size: 18),
          label: const Text('اشتراک متن'),
        ),
      ],
    );
  }

  /// Rebuilds the generated paragraph when a toggle that affects it changes.
  void _rebuild(ReportFacts facts, {required bool grades}) {
    setState(() {
      _includeGrades = grades;
      _textCtrl.text =
          buildReportParagraphs(facts, includeGrades: grades).join('\n\n');
    });
  }

  Widget _toggle(String label, bool value, ValueChanged<bool> onChanged) {
    final t = TimeThemeKit.of(context).palette;
    return SwitchListTile.adaptive(
      dense: true,
      contentPadding: EdgeInsets.zero,
      activeThumbColor: Personal2Colors.teacher,
      title: Text(
        label,
        style: TextStyle(
          fontFamily: AppTheme.fontFamily,
          fontSize: 12,
          color: t.textPrimary,
        ),
      ),
      value: value,
      onChanged: onChanged,
    );
  }

  ReportFacts _facts(StudentProfileState state, Personal2Templates? templates) {
    final now = DateTime.now();
    final j = Jalali.fromDateTime(now);
    final monthStart = '${j.year.toString().padLeft(4, '0')}-'
        '${j.month.toString().padLeft(2, '0')}-01';
    final todayKey = teacherDayKey(now);

    final lessons = state.lessons.map((l) => l.toSpec()).toList();
    final newPages = newPagesInRange(lessons, monthStart, todayKey);
    final tags = tagCounts(
      lessons.where((l) => l.dayKey.compareTo(monthStart) >= 0),
    );
    final suggestion = suggestNextAssignment(lessons);

    return ReportFacts(
      studentName: state.student.name,
      className: state.classGroup.name,
      fromDayKey: monthStart,
      toDayKey: todayKey,
      attendancePercent: state.attendancePct,
      newPages: newPages.length,
      highestPage: state.highest,
      averageGrade: _includeGrades ? state.averageGradeValue : null,
      topTagTitle: _includeMistakes && tags.isNotEmpty
          ? _tagTitle(templates, tags.first.tag)
          : null,
      nextAssignment:
          _includeNext && suggestion != null
              ? 'صفحهٔ ${suggestion.pageStart}'
              : null,
      teacherName: _includeTeacherName ? state.settings.teacherName : null,
    );
  }

  /// A tajweed tag's display label. The TAG asset is the authority — the
  /// grade scale lives in a different file and must never be consulted here,
  /// or a tag would print its key. Falls back to the key only when the asset
  /// is unavailable.
  String _tagTitle(Personal2Templates? templates, String key) {
    final tag = templates?.tagsTitle(key);
    return (tag == null || tag.isEmpty) ? key : tag;
  }

  Widget _previewCard(
    BuildContext context,
    StudentProfileState state,
    ReportFacts facts,
  ) {
    return Container(
      // A printed page, not an app surface: cream paper and a hairline, the
      // same family as the app's share cards.
      decoration: BoxDecoration(
        color: const Color(0xFFFDF8F0),
        borderRadius: BorderRadius.circular(18),
        border: Border.all(color: const Color(0xFFE6D9C6), width: 1.2),
      ),
      padding: const EdgeInsets.all(16),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Row(
            children: [
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      'گزارش پیشرفت',
                      style: TextStyle(
                        fontFamily: AppTheme.fontFamily,
                        fontSize: 14,
                        fontWeight: FontWeight.w700,
                        color: const Color(0xFF263238),
                      ),
                    ),
                    Text(
                      [
                        state.student.name,
                        state.classGroup.name,
                        if (state.settings.mosqueName.isNotEmpty)
                          state.settings.mosqueName,
                      ].join(' · '),
                      style: TextStyle(
                        fontFamily: AppTheme.fontFamily,
                        fontSize: 10,
                        color: const Color(0xFF78909C),
                      ),
                    ),
                  ],
                ),
              ),
              const Icon(Icons.menu_book_rounded,
                  size: 22, color: Personal2Colors.teacher),
            ],
          ),
          const Divider(height: 18, color: Color(0xFFE6D9C6)),
          Text(
            _textCtrl.text,
            style: TextStyle(
              fontFamily: AppTheme.fontFamily,
              fontSize: 12,
              height: 1.9,
              color: const Color(0xFF263238),
            ),
          ),
          const SizedBox(height: 10),
          Text(
            reportClosing(
              teacherName: _includeTeacherName
                  ? state.settings.teacherName
                  : null,
            ),
            style: TextStyle(
              fontFamily: AppTheme.fontFamily,
              fontSize: 11,
              color: const Color(0xFF78909C),
            ),
          ),
          const SizedBox(height: 8),
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Text(
                ShareService.signatureName,
                style: TextStyle(
                  fontFamily: AppTheme.fontFamily,
                  fontSize: 9,
                  color: const Color(0xFFB0A08C),
                ),
              ),
              Text(
                '${facts.fromDayKey} — ${facts.toDayKey}',
                style: TextStyle(
                  fontFamily: AppTheme.fontFamily,
                  fontSize: 9,
                  color: const Color(0xFFB0A08C),
                ),
              ),
            ],
          ),
        ],
      ),
    );
  }

  Future<void> _shareImage(StudentProfileState state) async {
    setState(() => _sharing = true);
    try {
      final bytes = await ReportRenderer.capturePng(_cardKey);
      if (bytes == null) {
        if (mounted) ShareService.showImageFailure(context);
        return;
      }
      await ReportRenderer.shareImage(
        bytes,
        fileName: 'teacher-report.png',
        text: 'گزارش ${state.student.name}\n${ShareService.channelBlock}',
      );
    } finally {
      if (mounted) setState(() => _sharing = false);
    }
  }

  Future<void> _sharePdf(StudentProfileState state, ReportFacts facts) async {
    setState(() => _sharing = true);
    try {
      final accent = PdfColor.fromInt(Personal2Colors.teacher.toARGB32());
      final Uint8List pdf = await ReportRenderer.buildPdf(
        title: 'گزارش پیشرفت',
        subtitle: [
          state.student.name,
          state.classGroup.name,
          if (state.settings.mosqueName.isNotEmpty) state.settings.mosqueName,
        ].join(' · '),
        accent: Personal2Colors.teacher,
        body: [
          pw.Text(
            _textCtrl.text,
            textDirection: pw.TextDirection.rtl,
            style: const pw.TextStyle(fontSize: 11, lineSpacing: 4),
          ),
          pw.SizedBox(height: 10),
          if (facts.attendancePercent != null)
            pdfRow(
              'حضور',
              '${(facts.attendancePercent! * 100).round()}٪',
              accent,
            ),
          if (facts.newPages > 0)
            pdfRow('صفحه‌های تازه', '${facts.newPages}', accent),
          if (facts.highestPage > 0)
            pdfRow('تا صفحهٔ', '${facts.highestPage}', accent),
          pw.SizedBox(height: 10),
          pw.Text(
            reportClosing(
              teacherName:
                  _includeTeacherName ? state.settings.teacherName : null,
            ),
            textDirection: pw.TextDirection.rtl,
            style: const pw.TextStyle(fontSize: 10),
          ),
        ],
      );
      await ReportRenderer.sharePdf(
        pdf,
        fileName: 'teacher-report.pdf',
        subject: 'گزارش ${state.student.name}',
      );
    } catch (e, st) {
      AppLogger.error('ParentReportScreen.sharePdf', e, st);
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text(
              'ساخت PDF ممکن نشد.',
              style: TextStyle(fontFamily: AppTheme.fontFamily),
            ),
          ),
        );
      }
    } finally {
      if (mounted) setState(() => _sharing = false);
    }
  }
}
