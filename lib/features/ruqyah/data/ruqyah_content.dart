/// یک قطعه محتوایی از یک فصل: می‌تواند عنوان، متن عربی (آیه/حدیث/دعا)،
/// ترجمه، توضیح فارسی و/یا فهرست نکات داشته باشد.
class RuqyahItem {
  final String? title;
  final String? arabic;
  final String? translation;
  final String? body;
  final List<String> bullets;

  const RuqyahItem({
    this.title,
    this.arabic,
    this.translation,
    this.body,
    this.bullets = const [],
  });
}

/// یک فصل از کتاب رقیه شرعی.
class RuqyahChapter {
  final String title;
  final IconData icon;
  final String? subtitle;
  final List<RuqyahItem> items;

  const RuqyahChapter({
    required this.title,
    required this.icon,
    this.subtitle,
    required this.items,
  });
}

