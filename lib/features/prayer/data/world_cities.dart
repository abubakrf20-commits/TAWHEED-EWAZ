/// Offline place table for users outside Iran.
///
/// The app already ships [iranProvinces] (1300+ Iranian towns), so an
/// offline name lookup worked only inside Iran: a user in Lagos, London or
/// Jakarta who typed their city got no match and was pushed onto the network
/// geocoder (or onto raw latitude/longitude entry). This table covers the
/// major cities of every inhabited continent — including the Muslim-majority
/// ones the prayer-time methods are named after — so a name typed anywhere on
/// earth resolves to coordinates with no network at all.
///
/// Coordinates are the city CENTRE in decimal degrees, north/east positive.
/// They only need kilometre-level accuracy: prayer times depend on latitude,
/// longitude and timezone, and 0.01° is about 1.1 km.
///
/// [WorldCity.tzId] is the city's IANA zone: picking the city manually must
/// render its times on ITS clock, not the device's (a Sydney picked from a
/// Tehran device used to shift every prayer by the zone gap).
class WorldCity {
  final String name;

  /// Persian name of the country, shown next to the city so two cities with
  /// the same name (قاهره in Egypt, سیدنی in Australia) stay distinguishable.
  final String country;
  final double lat;
  final double lng;

  /// IANA zone id for the city, or null when the zone is genuinely unknown.
  final String? tzId;

  const WorldCity(this.name, this.country, this.lat, this.lng, [this.tzId]);
}

