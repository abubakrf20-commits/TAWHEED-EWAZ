  /// The daily-verse list (public for tests and the notification service).
  static List<Map<String, String>> get dailyVerses => _dailyVerses;

  /// The daily-verse index for [date]. Shared by the app screen and the
  /// scheduled notification so both always show the same verse on the same
  /// day. Rotation is sequential: each day advances one step and after the
  /// last verse it wraps back to the first.
  static int dailyVerseIndexFor(DateTime date) =>
      _dayOfYear(date) % _dailyVerses.length;

  /// The verse of [date] — exactly what the daily notification shows.
  static Map<String, String> verseForDate(DateTime date) =>
      _dailyVerses[dailyVerseIndexFor(date)];

  static int _dayOfYear(DateTime date) =>
      date.difference(DateTime(date.year)).inDays;
