  /// The daily-hadith list (public for tests and the notification service).
  static List<Map<String, String>> get dailyHadiths => _dailyHadiths;

  /// The daily-hadith index for [date]. Shared by the app screen and the
  /// scheduled notification so both always show the same hadith on the same
  /// day. Rotation is sequential; the `+3` offset decouples the hadith index
  /// from the daily-verse index so the two lists do not restart in lockstep.
  static int dailyHadithIndexFor(DateTime date) =>
      (_dayOfYear(date) + 3) % _dailyHadiths.length;

  /// The hadith of [date] — exactly what the daily notification shows.
  static Map<String, String> hadithForDate(DateTime date) =>
      _dailyHadiths[dailyHadithIndexFor(date)];

  static int _dayOfYear(DateTime date) =>
      date.difference(DateTime(date.year)).inDays;
